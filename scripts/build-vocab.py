"""Builds src/rules/vocab.generated.ts from the team's working Excel.

For each category it lists the values the PASIA team actually uses in TYPE, ITEM_TYPE, CONFIGURATION, COLOR, SHAPE and the
word-sized values of DIMENSION/SIZE (1) (ADULT, INFANT...), plus "when ITEM_TYPE is X, TYPE is usually Y".
Run:  python -I scripts/build-vocab.py "<path to the working Excel>"
"""
import collections, json, sys
import openpyxl

path = sys.argv[1]
OUT = "src/rules/vocab.generated.ts"
COLS = {56: "TYPE", 77: "ITEM_TYPE", 74: "CONFIGURATION", 71: "COLOR", 70: "SHAPE", 63: "DIMENSION/SIZE (1)"}
CATS = {"CANNULA": "CANNULA", "CATHETERS": "CATHETERS", "NEEDLE": "NEEDLE", "SUTURE": "SUTURE"}
GENERIC_ITYPE = {"CONSUMABLE", "DEVICE", "INSTRUMENT", "EQUIPMENT"}  # these say nothing about the item

wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
rows = [r for r in wb.active.iter_rows(min_row=3, values_only=True) if r[0]]
out = {}
for cat in CATS:
    rs = [r for r in rows if r[1] == cat]
    vocab = {}
    for j, col in COLS.items():
        c = collections.Counter()
        for r in rs:
            v = r[j]
            if v in (None, ""):
                continue
            v = " ".join(str(v).upper().split())
            if ";" in v or len(v) > 28 or v in {"#N/A", "N/A", "NOT SURE", "0"}:
                continue
            if col == "ITEM_TYPE" and v in GENERIC_ITYPE:
                continue
            if col == "DIMENSION/SIZE (1)" and not v.replace(" ", "").isalpha():
                continue  # numbers (23G, 5ML) are read by pattern, not by word list
            c[v] += 1
        vocab[col] = [[v, n] for v, n in c.most_common(40) if n >= 3]
    # when ITEM_TYPE is X, which TYPE do people write?
    implies = {}
    pair = collections.defaultdict(collections.Counter)
    for r in rs:
        it, ty = r[77], r[56]
        if it in (None, "") or ty in (None, ""):
            continue
        it = " ".join(str(it).upper().split())
        if it in GENERIC_ITYPE:
            continue
        pair[it][" ".join(str(ty).upper().split())] += 1
    for it, c in pair.items():
        total = sum(c.values())
        ty, n = c.most_common(1)[0]
        if total >= 10 and n / total >= 0.7:
            implies[it] = [ty, n, total]
    out[cat] = {"rows": len(rs), "vocab": vocab, "typeGivenItemType": implies}

body = json.dumps(out, indent=1, ensure_ascii=False)
open(OUT, "w", encoding="utf-8").write(
    "/** Generated by scripts/build-vocab.py from the team's working Excel. Do not edit by hand. */\n"
    "export interface Vocab { rows: number; vocab: Record<string, [string, number][]>; typeGivenItemType: Record<string, [string, number, number]> }\n\n"
    f"export const VOCAB: Record<string, Vocab> = {body};\n")
for k, v in out.items():
    print(k, v["rows"], {c: len(x) for c, x in v["vocab"].items()}, "implies:", {a: b for a, b in list(v["typeGivenItemType"].items())[:4]})
